-- Sri Kangna CRM: Bookings — Chura booking + link bookings to Customers and Bills
-- Run once in Supabase → SQL Editor → New query → paste → Run. Safe to run again.

-- 1) Chura bookings
create table if not exists public.chura_bookings (
  id uuid primary key default gen_random_uuid(),
  booking_no bigint generated by default as identity,   -- shown as C-001, C-002 ...
  order_date date not null default current_date,         -- date of taking the order
  name text not null,
  mobile text,
  size text,
  chura_type text,
  colour text,
  give_date date,                                        -- date of giving (delivery)
  give_time time,
  rate numeric not null default 0,
  advance numeric not null default 0,
  adv_mode text not null default 'cash',                 -- advance paid by cash / upi
  note text,
  status text not null default 'booked',                 -- booked | ready | delivered | cancelled
  delivered_at timestamptz,
  customer_id uuid,
  bill_id uuid,
  created_at timestamptz not null default now()
);
create index if not exists chura_give_idx on public.chura_bookings (give_date);
alter table public.chura_bookings enable row level security;
drop policy if exists "Signed-in users manage chura_bookings" on public.chura_bookings;
create policy "Signed-in users manage chura_bookings" on public.chura_bookings
  for all to authenticated using (true) with check (true);

-- 2) Jewellery rent: link to customer + advance bill
alter table public.rentals add column if not exists customer_id uuid;
alter table public.rentals add column if not exists bill_id uuid;
alter table public.rentals add column if not exists adv_mode text not null default 'cash';

-- 3) Payment mode columns on bills (if not added before)
alter table public.bills add column if not exists pay_mode text not null default 'cash';
alter table public.bills add column if not exists cash_part numeric;
alter table public.bills add column if not exists card_part numeric;

-- 4) Add customers from existing rent bookings (only numbers not already in Customers)
insert into public.customers (name, phone, address, notes)
select distinct on (p) name, p, address, 'From jewellery rent booking'
from (
  select r.name, right(regexp_replace(r.mob1, '\D', '', 'g'), 10) as p, r.address, r.created_at
  from public.rentals r
  where length(regexp_replace(coalesce(r.mob1, ''), '\D', '', 'g')) >= 10
) x
where not exists (
  select 1 from public.customers c
  where right(regexp_replace(coalesce(c.phone, ''), '\D', '', 'g'), 10) = x.p
)
order by p, created_at desc;

-- link old rent bookings to their customer
update public.rentals r set customer_id = c.id
from public.customers c
where r.customer_id is null
  and length(regexp_replace(coalesce(r.mob1, ''), '\D', '', 'g')) >= 10
  and right(regexp_replace(coalesce(c.phone, ''), '\D', '', 'g'), 10) = right(regexp_replace(r.mob1, '\D', '', 'g'), 10);
